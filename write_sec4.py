'<h4>方案 A：ORM 作为 Verifier，接入标准 GRPO</h4>\n'
'<p>ORM 产出 \\([0,1]\\) 的连续分数，通过组内归一化转为优势估计，接入标准 GRPO：</p>\n'
'<pre><code class="language-python">def grpo_with_orm(policy, orm, prompts, group_size=8, beta=0.01):\n'
'    """方案 A：ORM 作为 Verifier 接入 GRPO，适合短轨迹（&lt;10 turns）"""\n'
'    all_losses = []\n'
'    for prompt in prompts:\n'
'        trajectories = [policy.generate(prompt) for _ in range(group_size)]\n'
'        rewards = torch.tensor([orm(tau) for tau in trajectories])\n'
'        # 组内归一化（GRPO 核心）\n'
'        normalized = (rewards - rewards.mean()) / (rewards.std() + 1e-8)\n'
'        for tau, A_hat in zip(trajectories, normalized):\n'
'            log_probs = policy.log_prob(tau, prompt)\n'
'            ref_log_probs = policy.ref_log_prob(tau, prompt)\n'
'            kl = (log_probs - ref_log_probs).sum()\n'
'            all_losses.append(-(A_hat * log_probs.sum()) + beta * kl)\n'
'    return torch.stack(all_losses).mean()</code></pre>\n'
