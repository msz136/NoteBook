'<h4>方案 B：PRM 产出 Dense Reward，接入 MT-GRPO</h4>\n'
'<p>PRM 为每个 turn 提供步骤级奖励，接入 MT-GRPO（Multi-Turn GRPO）的 turn-level advantage 计算：</p>\n'
'<pre><code class="language-python">def mt_grpo_with_prm(policy, prm, orm, prompts, group_size=8,\n'
'                      alpha=0.5, beta_kl=0.01, gamma=0.9):\n'
'    """方案 B：PRM Dense Reward 接入 MT-GRPO，适合长轨迹（10-30 turns）"""\n'
'    all_losses = []\n'
'    for prompt in prompts:\n'
'        trajectories = [policy.generate_multiturn(prompt) for _ in range(group_size)]\n'
'        for tau in trajectories:\n'
'            T = len(tau.turns)\n'
'            step_rewards = [prm(tau, t) for t in range(T)]\n'
'            episode_reward = orm(tau)\n'
'            combined = [alpha * episode_reward + (1-alpha) * step_rewards[t]\n'
'                        for t in range(T)]\n'
'            advantages = compute_gae(combined, gamma=gamma, lam=0.95)\n'
'            for t, (turn, A_t) in enumerate(zip(tau.turns, advantages)):\n'
'                log_probs = policy.log_prob_turn(turn, tau.context_up_to(t))\n'
'                ref_log_probs = policy.ref_log_prob_turn(turn, tau.context_up_to(t))\n'
'                kl = (log_probs - ref_log_probs).sum()\n'
'                all_losses.append(-(A_t * log_probs.sum()) + beta_kl * kl)\n'
'    return torch.stack(all_losses).mean()\n'
'\n'
'def compute_gae(rewards, gamma=0.9, lam=0.95):\n'
'    """广义优势估计（Generalized Advantage Estimation, GAE）"""\n'
'    T = len(rewards)\n'
'    advantages, gae = [0.0]*T, 0.0\n'
'    for t in reversed(range(T)):\n'
'        next_val = rewards[t+1] if t &lt; T-1 else 0\n'
'        delta = rewards[t] + gamma * next_val - rewards[t]\n'
'        gae = delta + gamma * lam * gae\n'
'        advantages[t] = gae\n'
'    return advantages</code></pre>\n'
'\n'
