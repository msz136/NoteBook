'<pre><code class="language-python">def grade_differentiable_reward(policy, reward_model, prompts,\n'
'                                  temperature=1.0, beta_kl=0.01):\n'
'    """方案 C：GRADE 可微分奖励，适合端到端联合训练"""\n'
'    all_losses = []\n'
'    for prompt in prompts:\n'
'        logits_seq = policy.forward(prompt)  # shape: (T, vocab_size)\n'
'        soft_tokens = []\n'
'        for logits in logits_seq:\n'
'            # Gumbel-Softmax 松弛（保持可微分）\n'
'            gumbel = -torch.log(-torch.log(torch.rand_like(logits) + 1e-20) + 1e-20)\n'
'            soft_tokens.append(F.softmax((logits + gumbel) / temperature, dim=-1))\n'
'        # 软化 token 嵌入\n'
'        soft_embs = [(s.unsqueeze(0) @ reward_model.embedding_matrix)\n'
'                     for s in soft_tokens]\n'
'        soft_traj = torch.cat(soft_embs, dim=1)\n'
'        reward = reward_model.score(soft_traj)  # 梯度可传回 logits\n'
