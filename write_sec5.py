'<h4>短轨迹（&lt; 10 turns）：GRPO with ORM Reward</h4>\n'
'<p>标准 GRPO 适合短轨迹场景，实现简单，计算开销低：</p>\n'
'\\[\n'
'\\mathcal{L}_{\\text{GRPO}} = -\\frac{1}{G} \\sum_{i=1}^{G} \\hat{A}_i \\log \\pi_\\theta(\\tau_i | x) + \\beta \\cdot \\text{KL}(\\pi_\\theta \\| \\pi_{\\text{ref}})\n'
'\\]\n'
'\\[\n'
