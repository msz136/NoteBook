'<h3>5.3 奖励 Hacking 防御</h3>\n'
'<p>奖励 Hacking（Reward Hacking）是 RL 训练中的核心风险：policy 学会欺骗奖励模型而非真正完成任务。以下三种防御策略可组合使用：</p>\n'
'\n'
'<h4>KL 惩罚</h4>\n'
'<p>在 RL 目标中加入与参考策略的 KL 散度惩罚，防止 policy 过度偏离预训练分布：</p>\n'
'\\[\n'
'\\mathcal{L}_{\\text{total}} = \\mathcal{L}_{\\text{RL}} + \\beta \\cdot \\text{KL}(\\pi_\\theta \\| \\pi_{\\text{ref}})\n'
'\\]\n'
'<p>推荐 \\( \\beta \\in [0.01, 0.05] \\)。\\( \\beta \\) 过大会限制 policy 的探索能力，\\( \\beta \\) 过小则无法防止奖励 hacking。</p>\n'
'\n'
'<h4>PRIME：隐式 PRM（避免奖励过拟合）</h4>\n'
'<p><strong>PRIME</strong>（arXiv:2502.01456）提出用语言模型本身的 token 概率作为隐式 PRM，避免显式训练 PRM 带来的过拟合风险：</p>\n'
'\\[\n'
'r_t^{\\text{PRIME}} = \\log \\frac{\\pi_{\\text{ref}}(a_t | s_t)}{\\pi_{\\text{base}}(a_t | s_t)}\n'
'\\]\n'
'<p>其中 \\( \\pi_{\\text{ref}} \\) 为经过 SFT 的参考策略，\\( \\pi_{\\text{base}} \\) 为预训练基础模型。这个比值衡量了 SFT 训练对该 token 的"偏好程度"，可作为步骤级奖励信号，无需额外训练 PRM。</p>\n'
'\n'
'<h4>DataPRM：三元奖励（区分探索性试错）</h4>\n'
'<p><strong>DataPRM</strong>（arXiv:2604.24198）提出三元奖励标签，区分三种步骤类型：</p>\n'
'<ul>\n'
'  <li><strong>正确步骤</strong>（+1）：直接推进任务完成的步骤</li>\n'
'  <li><strong>探索性试错</strong>（0）：虽然不是最优路径，但展现了合理的探索行为</li>\n'
'  <li><strong>错误步骤</strong>（-1）：导致任务失败或违反约束的步骤</li>\n'
'</ul>\n'
'<p>三元标签避免了将"探索性试错"惩罚为"错误"，鼓励 Agent 在不确定情况下进行合理探索。在 sandbox 场景中，可以通过分析步骤的最终影响来自动分配三元标签：</p>\n'
'<pre><code class="language-python">def assign_ternary_label(step, trajectory, sandbox, task):\n'
'    """\n'
'    DataPRM 三元标签分配\n'
'    +1: 正确步骤（该步后成功率显著提升）\n'
'     0: 探索性试错（该步后成功率未变或轻微下降，但步骤本身合理）\n'
'    -1: 错误步骤（该步后成功率显著下降，或违反约束）\n'
'    """\n'
'    # 计算该步前后的成功率变化\n'
'    success_before = estimate_success_rate(sandbox, trajectory[:step], task)\n'
'    success_after = estimate_success_rate(sandbox, trajectory[:step+1], task)\n'
'    delta = success_after - success_before\n'
'    \n'
'    # 检查是否违反约束\n'
'    if sandbox.check_forbidden_at_step(trajectory[step]):\n'
'        return -1  # 违反安全约束，直接标为错误\n'
'    \n'
'    if delta &gt; 0.1:\n'
'        return 1   # 显著提升，正确步骤\n'
'    elif delta &gt; -0.1:\n'
'        return 0   # 轻微变化，探索性试错\n'
'    else:\n'
'        return -1  # 显著下降，错误步骤</code></pre>\n'
'</section>\n'
