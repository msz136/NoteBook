'\\]\n'
'\n'
'<h4>中长轨迹（10-30 turns）：MT-GRPO with PRM Reward</h4>\n'
'<p>MT-GRPO（Multi-Turn GRPO，arXiv:2505.11821）在每个 turn 计算独立的优势估计，解决长轨迹中的信用分配问题：</p>\n'
'\\[\n'
'\\mathcal{L}_{\\text{MT-GRPO}} = -\\sum_{t=1}^{T} \\hat{A}_t^{\\text{turn}} \\log \\pi_\\theta(a_t | s_t, c_t) + \\beta \\cdot \\text{KL}_t\n'
'\\]\n'
'<p>其中 \\( \\hat{A}_t^{\\text{turn}} \\) 为第 \\( t \\) 个 turn 的优势估计，由 PRM 的步骤级奖励通过 GAE 计算得到。</p>\n'
'\n'
'<h4>长序列（&gt; 30 turns）：GAGPO with Dense PRM</h4>\n'
'<p>GAGPO（Group Advantage Guided Policy Optimization）通过组内对比和密集 PRM 奖励，在长序列场景下取得最优性能：</p>\n'
'\\[\n'
'\\mathcal{L}_{\\text{GAGPO}} = -\\sum_{t=1}^{T} \\min\\left(\\rho_t \\hat{A}_t, \\text{clip}(\\rho_t, 1-\\epsilon, 1+\\epsilon) \\hat{A}_t\\right) + \\beta \\cdot \\text{KL}\n'
'\\]\n'
'<p>其中 \\( \\rho_t = \\pi_\\theta(a_t) / \\pi_{\\text{old}}(a_t) \\) 为重要性采样比，\\( \\epsilon \\) 为 PPO clip 参数。</p>\n'
